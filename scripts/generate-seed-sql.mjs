// Generates supabase/migrations/0002_seed_data.sql by importing the existing
// JS seed modules and emitting INSERT statements that match the schema in
// 0001_initial_schema.sql.
//
// Run with: node scripts/generate-seed-sql.mjs
// Idempotent: re-running overwrites the SQL file with fresh UUIDs. The SQL
// itself is also idempotent (TRUNCATE at the top), so re-applying in
// Supabase will replace all seed rows.

import { randomUUID } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');

const importJs = (rel) => import(pathToFileURL(resolve(repoRoot, rel)).href);
const { DEFAULT_MEALS }   = await importJs('src/data/meals.js');
const { RECIPE_DATA }     = await importJs('src/data/recipes.js');
const { INGREDIENT_SEED } = await importJs('src/data/ingredientSeed.js');

// ── SQL escaping helpers ─────────────────────────────────────────────────────

const sqlString = (v) => {
  if (v === null || v === undefined || v === '') return 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const sqlText = (v) => {
  // Like sqlString but never returns NULL — for NOT NULL text columns.
  return `'${String(v ?? '').replace(/'/g, "''")}'`;
};

const sqlTextArray = (arr) => {
  if (!arr || arr.length === 0) return `'{}'`;
  const parts = arr.map(s => sqlText(s));
  return `ARRAY[${parts.join(', ')}]::text[]`;
};

const allowedMealCategories = new Set(['Beef','Chicken','Pork','Seafood','Vegetarian','Other']);
const allowedIngredientCategories = new Set([
  'Meat & Seafood','Produce','Dairy & Eggs','Bread & Pasta',
  'Canned & Jarred','Frozen','Pantry','Other',
]);

// ── Validate inputs early; fail loudly ───────────────────────────────────────

for (const meal of DEFAULT_MEALS) {
  if (!allowedMealCategories.has(meal.category)) {
    throw new Error(`Meal "${meal.name}" has invalid category: ${meal.category}`);
  }
}
for (const ing of INGREDIENT_SEED) {
  if (!allowedIngredientCategories.has(ing.category)) {
    throw new Error(`Ingredient "${ing.name}" has invalid category: ${ing.category}`);
  }
}

// ── Build SQL ────────────────────────────────────────────────────────────────

const lines = [];
lines.push('-- ============================================================================');
lines.push('-- HOME meal planner — seed data');
lines.push('-- ============================================================================');
lines.push('-- AUTO-GENERATED by scripts/generate-seed-sql.mjs — do not edit by hand.');
lines.push('-- Source: src/data/meals.js, src/data/recipes.js, src/data/ingredientSeed.js');
lines.push('-- ');
lines.push('-- This file is idempotent: it TRUNCATEs the seed tables first, so it can be');
lines.push('-- re-run to refresh seed data without manual cleanup. Per-user data in meals/');
lines.push('-- recipe_ingredients/ingredients is NOT affected (they have separate tables).');
lines.push('-- ');
lines.push('-- The TRUNCATE will fail if there are existing meals.source_seed_id references');
lines.push('-- (i.e. users have already signed up). In that case, either:');
lines.push('--   (a) accept that existing users keep their current copy and add a 0003 to');
lines.push('--       insert only the new seeds, or');
lines.push('--   (b) drop the FK constraint temporarily, truncate, re-seed, restore FK.');
lines.push('-- ============================================================================');
lines.push('');
lines.push('BEGIN;');
lines.push('');
lines.push('-- Wipe existing seed rows (CASCADE handles seed_recipe_ingredients).');
lines.push('-- Will fail if any meals.source_seed_id rows reference these.');
lines.push('TRUNCATE public.seed_meals, public.seed_ingredients RESTART IDENTITY CASCADE;');
lines.push('');

// ── seed_meals + seed_recipe_ingredients ─────────────────────────────────────

const mealIdMap = new Map(); // numeric meals.js id → uuid for seed_meals row

lines.push('-- ── seed_meals ──────────────────────────────────────────────────────────────');
lines.push('INSERT INTO public.seed_meals (id, name, category, tags, servings, prep_time, cook_time, instructions) VALUES');

const mealRows = DEFAULT_MEALS.map(meal => {
  const uuid = randomUUID();
  mealIdMap.set(meal.id, uuid);
  const recipe = RECIPE_DATA[meal.id];
  const tags = meal.tags ?? [];
  const servings    = recipe?.servings != null ? String(recipe.servings) : null;
  const prepTime    = recipe?.prepTime ?? null;
  const cookTime    = recipe?.cookTime ?? null;
  const instructions = recipe?.instructions ?? [];

  return `  (${sqlString(uuid)}, ${sqlText(meal.name)}, ${sqlText(meal.category)}, ${sqlTextArray(tags)}, ${sqlString(servings)}, ${sqlString(prepTime)}, ${sqlString(cookTime)}, ${sqlTextArray(instructions)})`;
});
lines.push(mealRows.join(',\n') + ';');
lines.push('');

// recipe_ingredients
const ingredientRows = [];
for (const meal of DEFAULT_MEALS) {
  const recipe = RECIPE_DATA[meal.id];
  if (!recipe?.ingredients?.length) continue;
  const seedMealUuid = mealIdMap.get(meal.id);

  recipe.ingredients.forEach((ing, idx) => {
    // Skip ingredient lines with no name — they're things like "salt to taste"
    // with an empty name in the source data, which would violate our NOT NULL.
    const name = (ing.name ?? '').trim();
    if (!name) return;

    ingredientRows.push(
      `  (${sqlString(seedMealUuid)}, ${idx}, ${sqlString(ing.quantity)}, ${sqlString(ing.unit)}, ${sqlText(name)})`
    );
  });
}

if (ingredientRows.length > 0) {
  lines.push('-- ── seed_recipe_ingredients ─────────────────────────────────────────────────');
  lines.push('INSERT INTO public.seed_recipe_ingredients (seed_meal_id, position, quantity, unit, name) VALUES');
  lines.push(ingredientRows.join(',\n') + ';');
  lines.push('');
}

// ── seed_ingredients ─────────────────────────────────────────────────────────

lines.push('-- ── seed_ingredients (library catalog) ──────────────────────────────────────');
lines.push('INSERT INTO public.seed_ingredients (name, default_qty, default_unit, alt_measure, category) VALUES');

const libRows = INGREDIENT_SEED.map(ing => {
  return `  (${sqlText(ing.name)}, ${sqlString(ing.defaultQty)}, ${sqlString(ing.defaultUnit)}, ${sqlString(ing.altMeasure)}, ${sqlText(ing.category)})`;
});
lines.push(libRows.join(',\n') + ';');
lines.push('');

lines.push('COMMIT;');
lines.push('');

// Summary footer
lines.push(`-- Summary: ${DEFAULT_MEALS.length} meals, ${ingredientRows.length} recipe ingredient lines, ${INGREDIENT_SEED.length} library ingredients.`);

const outPath = resolve(repoRoot, 'supabase/migrations/0002_seed_data.sql');
writeFileSync(outPath, lines.join('\n'), 'utf8');

console.log(`Wrote ${outPath}`);
console.log(`  ${DEFAULT_MEALS.length} seed meals`);
console.log(`  ${ingredientRows.length} seed recipe ingredient lines`);
console.log(`  ${INGREDIENT_SEED.length} seed library ingredients`);
